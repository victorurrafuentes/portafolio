tot <- totales_mensuales(agr);       write.csv(tot, "/tmp/r_tot.csv", row.names = FALSE)
cmp <- comparar_con_base(tot, "M18")
cat("comparar_con_base M18: monto x", round(cmp$razon_monto, 4), "| pago x", round(cmp$razon_pago, 4), "| recup x", round(cmp$razon_recup, 4), "\n")
